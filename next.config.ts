import type { NextConfig } from "next";

const securityHeaders = [
  { key: "X-Content-Type-Options", value: "nosniff" },
  { key: "X-Frame-Options", value: "DENY" },
  { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
  {
    key: "Permissions-Policy",
    value: "camera=(), microphone=(), geolocation=(), payment=(), usb=()",
  },
  {
    key: "Strict-Transport-Security",
    value: "max-age=63072000; includeSubDomains; preload",
  },
];

const nextConfig: NextConfig = {
  /* config options here */
  // cacheComponents (PPR) buys nothing here: every route is already forced
  // dynamic by the per-request CSP nonce in proxy.ts, so there's no static
  // shell left to partially prerender — and it fights plain dynamic APIs
  // like `new Date()` in Server Components.
  poweredByHeader: false,
  images: {
    // Only local, bundled assets are ever rendered — no remote patterns, which
    // removes an image-proxy/SSRF surface entirely.
    remotePatterns: [],
  },
  turbopack: {
    rules: {
      "*.css": {
        loaders: ["@tailwindcss/turbopack"],
        as: "*.css",
      },
    },
  },
  async headers() {
    return [
      {
        source: "/:path*",
        headers: securityHeaders,
      },
    ];
  },
};

export default nextConfig;
